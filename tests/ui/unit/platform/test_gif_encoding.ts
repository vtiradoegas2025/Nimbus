import assert from "node:assert/strict";
import { GifEncoding } from "../../../../ui/src/lib/platform/gifEncoding.ts";
import { GIF_MAX_FRAMES, validateGifSize } from "../../../../ui/src/lib/platform/gifLimits.ts";
for (const size of [[0, 10], [1.5, 2], [NaN, 2], [65536, 1], [4096, 2161]]) assert.throws(() => validateGifSize(...size as [number, number]));
const encoder = new GifEncoding(2, 2, 30);
const frame = new Uint8ClampedArray([255, 0, 0, 255, 0, 0, 255, 255, 255, 255, 255, 255, 0, 0, 0, 255]);
for (let i = 0; i < 3; i++) encoder.append(frame);
const bytes = encoder.finish();
assert.equal(new TextDecoder().decode(bytes.subarray(0, 6)), "GIF89a");
assert.equal(bytes[bytes.length - 1], 0x3b);
const delays: number[] = [];
for (let i = 0; i < bytes.length - 8; i++) if (bytes[i] === 0x21 && bytes[i+1] === 0xf9 && bytes[i+2] === 4) delays.push(bytes[i+4] + bytes[i+5]*256);
assert.deepEqual(delays, [3, 4, 3]);
assert.throws(() => encoder.append(frame));
assert.throws(() => encoder.finish());
assert.throws(() => new GifEncoding(2, 2, 10, 2048).append(frame), /memory limit/);
assert.throws(() => new GifEncoding(2, 2, 10).append(new Uint8ClampedArray(4)), /dimensions/);
const bounded = new GifEncoding(1, 1, 10);
for (let i = 0; i < GIF_MAX_FRAMES; i++) bounded.append(new Uint8ClampedArray([0, 0, 0, 255]));
assert.throws(() => bounded.append(new Uint8ClampedArray([0, 0, 0, 255])), /frame limit/);
console.log("GIF cadence, size, encoded-byte and frame bounds passed");
