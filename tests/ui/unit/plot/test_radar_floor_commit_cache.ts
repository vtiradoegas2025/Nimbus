import assert from "node:assert/strict";
import { RadarFloorCommitCache } from "../../../../ui/src/lib/plot/radarFloorCommitCache.ts";
const cache = new RadarFloorCommitCache();
const rgba = new Uint8ClampedArray([1, 2, 3, 4]);
const input = { texture: {}, rgba, shape: "1:1", geometry: "native-plane-0" };
let geometry = 0, uploads = 0;
const apply = (next = input) => cache.apply(next, () => { geometry++; }, () => { uploads++; });
apply();
for (let edit = 0; edit < 100; edit++) apply({ ...input });
assert.deepEqual([geometry, uploads], [1, 1], "opacity/threshold renders do not reconstruct or reupload unchanged floor inputs");
apply({ ...input, geometry: "native-plane-scaled" });
assert.deepEqual([geometry, uploads], [2, 1]);
const changed = { ...input, geometry: "native-plane-scaled", rgba: rgba.slice() };
apply(changed);
assert.deepEqual([geometry, uploads], [2, 2]);
apply({ ...changed, shape: "2:1" });
assert.deepEqual([geometry, uploads], [2, 3]);
const restored = { ...changed, texture: {} };
apply(restored);
assert.deepEqual([geometry, uploads], [3, 4], "context restoration always populates the fresh texture");
cache.reset(); apply(restored);
assert.deepEqual([geometry, uploads], [4, 5]);
const failed = { ...restored, rgba: rgba.slice(), geometry: "terrain-1" };
assert.throws(() => cache.apply(failed, () => { geometry++; }, () => { throw Error("upload failed"); }), /upload failed/);
apply(failed);
assert.deepEqual([geometry, uploads], [6, 6], "a failed stage is never memoized as a committed texture");
assert.deepEqual([...rgba], [1, 2, 3, 4]);
console.log("Floor commit cache avoids100 redundant uploads/geometries while preserving encoding, shape, geometry, lifecycle, failure retry, and source bytes");
