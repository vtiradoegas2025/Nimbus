import assert from "node:assert/strict";
import { beginPlotCanvasOperation, isPlotCanvasReceiptCurrent, retirePlotCanvas, waitForPlotCanvasReady } from "../../../../ui/src/lib/plot/plotCanvasReadiness.ts";

const element = { isConnected: true } as HTMLElement;
const first = beginPlotCanvasOperation(element);
let resolved = false;
const waiting = waitForPlotCanvasReady(element).then(receipt => { resolved = true; return receipt; });
const resize = beginPlotCanvasOperation(element, "resize");
first();
await Promise.resolve();
assert.equal(resolved, false, "capture waits for queued resize as well as traces");
resize();
const receipt = await waiting;
assert.equal(isPlotCanvasReceiptCurrent(receipt), true);
const next = beginPlotCanvasOperation(element);
assert.equal(isPlotCanvasReceiptCurrent(receipt), false, "committed updates invalidate prior pixels");
next(new Error("render failed"));
const laterResize = beginPlotCanvasOperation(element, "resize");
laterResize();
await assert.rejects(waitForPlotCanvasReady(element), /render failed/, "resize cannot conceal failed traces");
const obsolete = beginPlotCanvasOperation(element);
const latest = beginPlotCanvasOperation(element);
obsolete(new Error("obsolete failure"));
latest();
assert.equal(isPlotCanvasReceiptCurrent(await waitForPlotCanvasReady(element)), true);
const held = beginPlotCanvasOperation(element);
await assert.rejects(waitForPlotCanvasReady(element, 1), /did not finish/);
const retired = assert.rejects(waitForPlotCanvasReady(element), /changed/);
retirePlotCanvas(element);
await retired;
held();
await assert.rejects(waitForPlotCanvasReady(element), /no longer available/);
const remount = beginPlotCanvasOperation(element);
remount();
assert.equal(isPlotCanvasReceiptCurrent(receipt), false, "remount cannot revive an old receipt");
assert.equal(isPlotCanvasReceiptCurrent(await waitForPlotCanvasReady(element)), true);
retirePlotCanvas(element);
console.log("Plot capture readiness: 10 ownership, queue, failure and retirement checks passed.");
