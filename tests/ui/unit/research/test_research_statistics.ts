import assert from "node:assert/strict";
import { ResearchAccumulator, binIndex, binCenters, type ScanSpec } from "../../../../ui/src/lib/research/statistics.ts";
import { cacheResearchScan, cachedResearchScan, clearResearchScanCache, researchScanCacheBytes } from "../../../../ui/src/lib/research/scanCache.ts";
const spec: ScanSpec = { value: { min: -4, max: 4, bins: 4 }, height: { min: 0, max: 2, bins: 2 }, joint: { min: 0, max: 4, bins: 4 }, threshold: -2, below: true, reflectivity: false, axesM: [[500, 1500], [500], [500, 1500]], cellAreaM2: 1e6, cellVolumeM3: 1e9, footprint: { x: { min: 0, max: 2, bins: 2 }, y: { min: 0, max: 1, bins: 2 } } };
const accumulator = new ResearchAccumulator(spec);
accumulator.append({ origin: [0, 0, 0], shape: [2, 1, 2], values: new Float32Array([-3, -1, -2, NaN]), other: new Float32Array([1, 2, 3, 0]) });
const r = accumulator.finish();
assert.equal(r.finite, 3);
assert.equal(r.missing, 1);
assert.equal(r.selected, 2);
assert.equal(r.mean, -2);
assert.equal(r.selectedMean, -2.5);
assert.equal(r.areaKm2, 2);
assert.equal(r.volumeKm3, 2);
assert.equal(r.massKg, null);
assert.deepEqual(r.heightCounts, [2, 1]);
assert.deepEqual(r.heightMeans, [-2.5, -1]);
assert.equal(r.cfad[0].reduce((a, b) => a + b, 0), 100);
assert.equal(r.cfad[1].reduce((a, b) => a + b, 0), 100);
const missingOnly = new ResearchAccumulator({ ...spec, joint: undefined });
missingOnly.append({ origin: [0, 0, 0], shape: [1, 1, 2], values: new Float32Array([NaN, NaN]) });
assert.equal(missingOnly.finish().areaKm2, null);
assert.equal(missingOnly.finish().volumeKm3, null);
const chunked = new ResearchAccumulator(spec);
chunked.append({ origin: [0, 0, 0], shape: [1, 1, 2], values: new Float32Array([-3, -1]), other: new Float32Array([1, 2]) });
chunked.append({ origin: [1, 0, 0], shape: [1, 1, 2], values: new Float32Array([-2, NaN]), other: new Float32Array([3, 0]) });
assert.deepEqual(chunked.finish(), r, "tile partitioning must not alter statistics");
assert.equal(binIndex(4, spec.value), 3);
assert.equal(binIndex(4.1, spec.value), -1);
assert.deepEqual(binCenters(spec.value), [-3, -1, 1, 3]);
const log = new ResearchAccumulator({ ...spec, joint: undefined, footprint: undefined, value: { min: 0, max: 20, bins: 2 }, reflectivity: true });
log.append({ origin: [0, 0, 0], shape: [1, 1, 2], values: new Float32Array([0, 20]) });
assert(Math.abs(log.finish().mean! - 10 * Math.log10(50.5)) < 1e-12);
const masked = new ResearchAccumulator({ ...spec, maskThreshold: 5 });
assert.throws(() => masked.append({ origin: [0, 0, 0], shape: [1, 1, 2], values: new Float32Array([1, 2]), other: new Float32Array([1, 2]) }), /mask/);
masked.append({ origin: [0, 0, 0], shape: [1, 1, 2], values: new Float32Array([-3, -1]), other: new Float32Array([1, 2]), mask: new Float32Array([5, NaN]) });
assert.equal(masked.finish().finite, 1);
assert.equal(masked.finish().masked, 1);
const mass = new ResearchAccumulator({ ...spec, joint: undefined, footprint: undefined, threshold: 0, below: false, massFactor: .001 });
mass.append({ origin: [0, 0, 0], shape: [1, 1, 2], values: new Float32Array([1, 3]), density: new Float32Array([2, 2]) });
assert.equal(mass.finish().massKg, 8000000);
const terrain = new ResearchAccumulator({ ...spec, joint: undefined, cellVolumeM3: null });
terrain.append({ origin: [0, 0, 0], shape: [1, 1, 2], values: new Float32Array([-3, -3]), centroids: { x: new Float64Array([500, 500]), y: new Float64Array([500, 500]), z: new Float64Array([1200, 1800]) }, volumes: new Float64Array([2, 4]) });
assert.deepEqual(terrain.finish().heightCounts, [0, 2]);
assert.equal(terrain.finish().volumeKm3, 6e-9);
const outside = new ResearchAccumulator({ ...spec, joint: undefined, value: { min: 0, max: 4, bins: 4 } });
outside.append({ origin: [0, 0, 0], shape: [1, 1, 2], values: new Float32Array([-3, 7]) });
assert.equal(outside.finish().belowRange, 1);
assert.equal(outside.finish().aboveRange, 1);
assert.deepEqual(outside.finish().cfad[0], [0, 0, 0, 0]);
assert.throws(() => new ResearchAccumulator({ ...spec, value: { min: 4, max: 4, bins: 4 } }));
assert.throws(() => new ResearchAccumulator({ ...spec, cellAreaM2: -1 }));
clearResearchScanCache();
cacheResearchScan("source-a", r);
const copy = cachedResearchScan("source-a")!;
copy.valueCounts[0] = 999;
assert.notEqual(cachedResearchScan("source-a")!.valueCounts[0], 999);
assert.equal(cachedResearchScan("source-b"), null);
assert(researchScanCacheBytes() > 0);
clearResearchScanCache();
assert.equal(researchScanCacheBytes(), 0);
console.log("Research statistics: native cells, boundaries, gaps, masks, tile invariance, reflectivity, terrain volume, mass and cache ownership passed");
