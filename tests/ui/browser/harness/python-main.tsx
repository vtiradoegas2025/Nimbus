/*
 * Python scripting harness.
 *
 * The Python tab had no end-to-end coverage for one reason: it booted CPython
 * from a CDN, so every spec would have depended on network weather and taken
 * a multi-megabyte download per run. The browser-test build now points the
 * runtime at a locally vendored copy of the same pinned release
 * (../tests/ui/vendor_pyodide.mjs), which makes a real interpreter cheap enough to
 * assert against. These specs run actual Python -- not a stand-in that would
 * agree with whatever the UI asked of it.
 *
 * `?keep=1` preserves the persisted workspace, for the one spec that checks
 * recovery across a reload. Without it the store is cleared on load so each
 * spec starts from the same starter script rather than from whatever the
 * previous spec left behind.
 */

/*
 * The run store, readable from a spec.
 *
 * The panel's results now outlive the panel, which means a spec that unmounts
 * it has no DOM to assert against — and "the figure came back" and "the figure
 * was never stored" look identical from outside. This is the only way to tell
 * the two apart when the assertion fails.
 */
(window as unknown as Record<string, unknown>).__nimbusPythonSession = (
  projectId: string | null,
  paneId: string,
) => {
  const session = readSession(sessionKey(projectId, paneId));
  return {
    running: session.running,
    completedRuns: session.completedRuns,
    datasetToken: session.datasetToken,
    cellRunCount: session.cellRuns.size,
    lastRunCellIndices: [...session.lastRunCellIndices],
    loadErr: session.loadErr,
    ioStatus: session.ioStatus,
  };
};

