async function executeProvider(source: string, terrain = false, geometry?: "index" | "translated" | "cylindrical"): Promise<{ values: number[]; shape: readonly number[] }> {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(source));
  const sourceDigest = `sha256:${Array.from(new Uint8Array(digest), byte => byte.toString(16).padStart(2, "0")).join("")}`;
  const provider = parseExternalDerivedProvider({
    schema: EXTERNAL_DERIVED_PROVIDER_SCHEMA, schemaVersion: 1, definitionVersion: 1,
    id: "test_python_values", kind: "python", label: "Test Python values", description: "Bounded precision and result ownership fixture",
    providerVersion: "1.0.0", enabled: true, permissions: ["execute-python", "read-frame-fields"],
    capabilities: ["derived-field", "numpy"], inputs: [{ fieldId: "w", alias: "w", unit: "m/s" }],
    output: { fieldId: "test_python_values", label: "Test values", unit: "m/s", category: "custom", shapePolicy: { kind: "exact", dimensions: [2] } },
    entrypoint: { runtime: "pyodide", runtimeVersion: "0.26.4", source, sourceDigest, resultVariable: "result" },
  });
  const result = await executeExternalDerivedProvider(provider, createPyodideDerivedProviderAdapter(), {
    requestId: "python-provider-fixture", datasetIdentity: "python-provider-fixture",
    grid: terrain ? { nr: 4, nth: 4, nz: 4, coordinateSystem: "cartesian", drM: 10, dyM: 10, dzM: 100, terrainFollowing: true,
      scalarCoordinatesM: [[10, 20, 30, 40], [5, 15, 25, 35], [100, 200, 300, 400]],
      validIndexRange: { lower: [1, 1, 1], upper: [2, 2, 3] } }
      : geometry ? { nr: 2, nth: 2, nz: 2, coordinateSystem: geometry === "cylindrical" ? "cylindrical" : "cartesian",
        geometryKind: geometry === "index" ? "index" : "physical", drM: 10, dyM: 20, dzM: 30, dthetaRad: 0.5,
        scalarOriginM: [100, 200, 300], horizontalScalarOriginM: [-999, -999],
        ...(geometry === "translated" ? { scalarCoordinatesM: [[100, 115], [200, 225], [300, 345]] as [number[], number[], number[]] } : {}) }
      : null,
    frame: { index: terrain ? 42 : 0, simulationTimeS: terrain ? 300 : 0, publicationGeneration: "fixture" },
    inputs: { w: { field: terrain ? { shape: [2, 2, 2], data: Float32Array.from({ length: 8 }, (_, index) => index + 1),
      windowGeometry: { sourceShape: [4, 4, 4], origin: [1, 1, 2], extent: [2, 2, 2], stride: [1, 1, 1],
        aggregation: "point_sample", weighting: "physical_cell_volume", sampleLocation: "physical_volume_centroid", sourceFormat: "npy",
        centroidsM: { x: Float64Array.from({ length: 8 }, (_, index) => 20 + Math.floor(index / 4) * 10),
          y: Float64Array.from({ length: 8 }, (_, index) => 15 + Math.floor(index / 2) % 2 * 10),
          z: Float64Array.from({ length: 8 }, (_, index) => 300 + index % 2 * 100 + Math.floor(index / 2) * 5) } } }
      : geometry ? { shape: [2, 2, 2], data: Float32Array.from({ length: 8 }, (_, index) => index + 1) }
      : { shape: [2], data: Float32Array.of(1, 2) }, unit: "m/s", identity: "fixture" } },
    grantedPermissions: new Set(["execute-python", "read-frame-fields"]), signal: new AbortController().signal,
  });
  return { shape: result.field.shape, values: Array.from(result.field.data) };
}

async function verifyProviderCache() {
  const runDir = PACKAGED_ATMOSPHERIC_EXAMPLES[0].uri;
  const frames = await listSteps(runDir);
  const frame = frames[0];
  const code = "result = source.copy()";
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(code));
  const sourceDigest = `sha256:${Array.from(new Uint8Array(digest), byte => byte.toString(16).padStart(2, "0")).join("")}`;
  const definition = (fieldId: "u" | "v") => parseExternalDerivedProvider({
    schema: EXTERNAL_DERIVED_PROVIDER_SCHEMA, schemaVersion: 1, definitionVersion: 1,
    id: "test_cached_copy", kind: "python", label: "Test cached copy", description: "Ordinary read path cache and provenance fixture",
    providerVersion: "1.0.0", enabled: true, permissions: ["execute-python", "read-frame-fields"], capabilities: ["derived-field", "numpy"],
    inputs: [{ fieldId, alias: "source", unit: frame.fieldUnits[fieldId] }],
    output: { fieldId: "test_cached_copy", label: "Copy", unit: frame.fieldUnits[fieldId], category: "dynamics", shapePolicy: { kind: "match-input", inputAlias: "source" } },
    entrypoint: { runtime: "pyodide", runtimeVersion: "0.26.4", source: code, sourceDigest, resultVariable: "result" },
  });
  const u = await readFieldAny(runDir, frame.index, "u", frame.publicationGeneration);
  const v = await readFieldAny(runDir, frame.index, "v", frame.publicationGeneration);
  const read = async (fieldId: "u" | "v") => {
    registerExternalDerivedProviders(runDir, runDir, frames, [definition(fieldId)]);
    return readFieldAny(runDir, frame.index, "test_cached_copy", frame.publicationGeneration);
  };
  const first = await read("u");
  const second = await read("v");
  const warm = await read("u");
  const provenance = externalDerivedFieldProvenance(runDir, frame.index, "test_cached_copy", frame.publicationGeneration);
  const equals = (left: Float32Array, right: Float32Array) => left.length === right.length && left.every((value, index) => Object.is(value, right[index]));
  return {
    shape: u.shape,
    uMatches: equals(first.data, u.data), vMatches: equals(second.data, v.data), warmMatches: equals(warm.data, u.data),
    distinctInputs: !equals(u.data, v.data), warmReused: warm.data === first.data,
    warmInputIdentity: provenance?.inputIdentities.source,
    expectedIdentity: makeFieldKey(runDir, frame.index, "u", frame.publicationGeneration),
  };
}

