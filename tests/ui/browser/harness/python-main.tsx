let heldScriptIo: { command: "read_config" | "write_config"; path: string; arrived: boolean;
  waiting: Promise<void>; release: () => void; timeout: ReturnType<typeof setTimeout> } | null = null;
function holdScriptIo(command: "read_config" | "write_config", path: string): void {
  if (heldScriptIo) throw new Error("A script I/O operation is already held");
  let release!: () => void;
  const waiting = new Promise<void>(resolve => { release = resolve; });
  heldScriptIo = { command, path, arrived: false, waiting, release, timeout: setTimeout(release, 15_000) };
}
function releaseScriptIo(): void {
  if (!heldScriptIo) return;
  clearTimeout(heldScriptIo.timeout);
  heldScriptIo.release();
}
installTauriFixture({ intercept: async (command, payload) => {
  const held = heldScriptIo;
  if (held && command === held.command && (payload as { path?: string } | null)?.path === held.path) {
    held.arrived = true;
    await held.waiting;
    clearTimeout(held.timeout);
    if (heldScriptIo === held) heldScriptIo = null;
  }
  return null;
} });

