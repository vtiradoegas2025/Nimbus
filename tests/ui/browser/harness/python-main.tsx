/*
 * Stands in for Studio's open project.
 *
 * The tab keeps one editor recovery store per project, so the behaviour worth
 * testing is not "it mounts with an id" but what happens ACROSS a switch:
 * whether the outgoing project's buffers are filed under the outgoing key
 * before the incoming ones load. That needs the id to change on a live mount,
 * which a URL parameter alone cannot do.
 */
const HARNESS_PROJECTS = ["project_alpha", "project_beta"] as const;

/*
 * `?panes=2` mounts a second tab in a companion pane.
 *
 * Studio lets a user pick the Python type for a companion pane, so two of these
 * can be on screen at once — and they then keep separate editor recovery
 * stores. Nothing about that is observable from one instance, so the harness
 * has to be able to raise two.
 */
const PANE_IDS = params.get("panes") === "2"
  ? (["primary", "companion-0"] as const)
  : (["primary"] as const);

function PythonHarness() {
  const [projectId, setProjectId] = useState<string | null>(params.get("project"));
  /*
   * Studio's own navigation, reduced to its essential act.
   *
   * `PageView` in App.tsx is a switch: leaving the Plots page does not hide the
   * studio, it unmounts it. That is the whole mechanism behind "clicking off
   * killed my run", and it cannot be reproduced from inside a panel that is
   * always mounted — so the harness has to be able to take it away and put it
   * back, exactly as the router does.
   */
  const [mounted, setMounted] = useState(true);
  return (
    <div style={{ display: "flex", flexDirection: "column", height: "100%" }}>
      <label
        style={{ display: "flex", gap: 8, alignItems: "center", padding: 4, flex: "0 0 auto" }}
      >
        <span>Harness project</span>
        <select
          aria-label="Harness project"
          value={projectId ?? ""}
          onChange={(event) => setProjectId(event.target.value || null)}
        >
          <option value="">(no project)</option>
          {HARNESS_PROJECTS.map((id) => <option key={id} value={id}>{id}</option>)}
        </select>
        <input
          type="checkbox"
          aria-label="Panel mounted"
          checked={mounted}
          onChange={(event) => setMounted(event.target.checked)}
        />
      </label>
      {!mounted && <div data-harness-unmounted="1">panel unmounted</div>}
      <div style={{ flex: "1 1 auto", minHeight: 0, display: "flex" }}>
        {mounted && PANE_IDS.map((paneId) => (
          <div
            key={paneId}
            data-harness-pane={paneId}
            style={{ flex: "1 1 0", minWidth: 0, minHeight: 0 }}
          >
            <PaneProvider
              value={{
                bus: null,
                paneId,
                cameraLocked: false,
                cameraAuthority: true,
                voxelBudgetScale: 1,
                ownsSharedOverlays: paneId === "primary",
              }}
            >
              {/*
                * `?frames=none` mounts the tab with nothing open at all.
                *
                * Studio's Python tab is reachable before a run has been
                * selected, and an interpreter needs no dataset to be useful —
                * the starter script draws its own figure in that state. That
                * used to be untestable here because the harness always had a
                * fixture: with no way to mount an empty tab, the branch where
                * Run has no frame to bind was only ever exercised by users.
                */}
              <PythonPlot
                runDir={params.get("frames") === "none" ? "" : primaryRunDir}
                steps={params.get("frames") === "none" ? [] : primarySteps}
                stepIdx={0}
                datasets={
                  params.get("single") === "1" || params.get("frames") === "none"
                    ? undefined
                    : datasets
                }
                projectId={projectId}
              />
            </PaneProvider>
          </div>
        ))}
      </div>
    </div>
  );
}

