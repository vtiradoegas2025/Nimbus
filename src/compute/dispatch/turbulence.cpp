bool dispatch_smagorinsky_fused_backend(ComputeBackendRuntimeState& compute,
                                        const float*                u_data,
                                        const float*                v_data,
                                        const float*                w_data,
                                        const float*                theta_data,
                                        const float*                qv_data,
                                        const float*                dz_prof,
                                        const float*                dzc_prof,
                                        const float*                rho,
                                        int                         prof_len,
                                        float*                      nu_t,
                                        float*                      K_theta,
                                        float*                      K_q,
                                        float*                      dudt_sgs,
                                        float*                      dvdt_sgs,
                                        float*                      dwdt_sgs,
                                        float*                      dthetadt_sgs,
                                        float*                      dqvdt_sgs,
                                        int                         nx,
                                        int                         ny,
                                        int                         nz,
                                        int                         filter_mode,
                                        bool                        use_horizontal,
                                        bool                        use_vertical,
                                        bool                        has_qv,
                                        bool                        periodic_x,
                                        bool                        periodic_y,
                                        float                       dx_val,
                                        float                       dy_val,
                                        float                       Cs,
                                        float                       Pr_t,
                                        float                       Sc_t,
                                        float                       nu_t_max,
                                        float                       K_max,
                                        bool                        download_coefficients,
                                        std::array<bool, 4>         open_lateral)
{
    TurbulenceComputeKernels* kernels = active_turbulence_kernels(compute);
    if (kernels != nullptr && kernels->supports(TurbulenceKernelOp::Smagorinsky))
    {
        const SmagorinskyFusedDispatch dispatch{u_data,       v_data,
                                                w_data,       theta_data,
                                                qv_data,      dz_prof,
                                                dzc_prof,     rho,
                                                prof_len,     nu_t,
                                                K_theta,      K_q,
                                                dudt_sgs,     dvdt_sgs,
                                                dwdt_sgs,     dthetadt_sgs,
                                                dqvdt_sgs,    nx,
                                                ny,           nz,
                                                filter_mode,  use_horizontal,
                                                use_vertical, has_qv,
                                                periodic_x,   periodic_y,
                                                dx_val,       dy_val,
                                                Cs,           Pr_t,
                                                Sc_t,         nu_t_max,
                                                K_max,        download_coefficients, open_lateral};
        return kernels->dispatch_smagorinsky_fused(dispatch);
    }
    return false;
}

