#!/usr/bin/env python3
"""Check solver module/selector coverage and generate the manuals' source index."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[3]
SOURCES = ROOT / 'scripts/dev/docs/latex'


def tex_escape(value: str) -> str:
    return value.replace('_', r'\_').replace('&', r'\&')


def render(value: dict) -> str:
    lines = [
        r'% Generated by scripts/dev/docs/check_solver_coverage.py --write.',
        r'\chapter{Solver source and scheme coverage}\label{solver-source-coverage}',
        '',
        'This index connects every top-level solver directory under',
        r'\texttt{include/} and \texttt{src/} to the mathematical discussion.',
        r'The \href{ARCHITECTURE.pdf}{architecture guide} provides the corresponding',
        'module ownership, dataflow and execution contracts. Infrastructure,',
        'utilities and provisioning tools support these operators; they do not',
        'introduce additional atmospheric equations merely by existing in source.',
        '',
        r'\begin{longtable}{@{}p{0.23\linewidth}p{0.72\linewidth}@{}}',
        r'\toprule Subsystem & Source and mathematical discussion \\ \midrule',
        r'\endhead\bottomrule\endfoot',
    ]
    for module in value['modules']:
        roots = ', '.join(r'\href{../' + p + '}{' + ('interfaces' if p.startswith('include/') else 'implementation') + '}' for p in module['roots'])
        label = module['id'].replace('_', ' ').capitalize()
        lines.append(tex_escape(label) + ' & ' + roots + r'; \hyperref[' + module['mathematics_anchor'] + r']{theory, conventions and limits}. \\')
    lines += [r'\end{longtable}', '', r'\section{Canonical scheme selectors}',
              'The following IDs are the canonical entries in the generated runtime',
              'catalog. Aliases and additional typed options are described by their',
              'configuration owners. A listed constructor does not establish that',
              'every grid, physics, output and backend combination is admitted.', '',
              r'\begin{longtable}{@{}p{0.22\linewidth}p{0.73\linewidth}@{}}',
              r'\toprule Catalog family & Canonical IDs \\ \midrule',
              r'\endhead\bottomrule\endfoot']
    for name, identifiers in value['catalog_selectors'].items():
        ids = ', '.join(r'\path{' + identifier + '}' for identifier in identifiers)
        lines.append(tex_escape(name.replace('_', ' ').capitalize()) + ' & ' + ids + r' \\')
    lines += [r'\end{longtable}', '',
              'Initialization additionally separates file/parametric sounding sources,',
              'hodograph precedence and none/bubble/vortex triggers. Surface exchange',
              'and simple-grey optical-model selections are distinct typed choices',
              'within their owners. Those paths are explained in the initialization,',
              'radiation and mixing chapters rather than inferred from this catalog table.', '',
              'The coverage check detects missing module or catalog entries and broken',
              'chapter references. It cannot prove that a derivation is correct, that a',
              'paper has been implemented completely or that a capability is qualified.',
              'Source review, mathematical checks, bounded tests and independent',
              'scientific review remain separate requirements.', '']
    return '\n'.join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    value = json.loads((SOURCES / 'solver-coverage.json').read_text())
    actual = {p.relative_to(ROOT).as_posix() for base in ['include', 'src']
              for p in (ROOT / base).iterdir() if p.is_dir() and not p.name.startswith('.') and p.name != '__pycache__'}
    listed = [p for module in value['modules'] for p in module['roots']]
    if len(listed) != len(set(listed)) or set(listed) != actual:
        parser.error(f'module coverage differs: missing={sorted(actual-set(listed))}, extra={sorted(set(listed)-actual)}')
    catalog = json.loads((ROOT / 'ui/src/lib/config/nativeCatalogSnapshot.json').read_text())
    selectors = {m['id']: [s['id'] for s in m['schemes']] for m in catalog['modules']}
    if selectors != value['catalog_selectors']:
        parser.error('catalog selectors changed; update their documentation and coverage index')
    math = '\n'.join(p.read_text() for p in SOURCES.glob('mathematics*.tex') if p.name != 'mathematics-coverage.tex')
    architecture = '\n'.join(p.read_text() for p in SOURCES.glob('architecture*.tex'))
    math_labels = set(re.findall(r'\\label\{([^}]+)\}', math))
    architecture_labels = set(re.findall(r'\\label\{([^}]+)\}', architecture))
    for module in value['modules']:
        if module['mathematics_anchor'] not in math_labels or module['architecture_anchor'] not in architecture_labels:
            parser.error(f'missing chapter anchor for {module["id"]}')
        for source in module['roots']:
            if r'\href{../' + source + '}' not in architecture:
                parser.error(f'architecture does not link its module owner: {source}')
    path = SOURCES / 'mathematics-coverage.tex'
    generated = render(value)
    if args.write:
        path.write_text(generated)
    elif not path.exists() or path.read_text() != generated:
        parser.error('source index changed; run check_solver_coverage.py --write')
    print(f'Solver coverage verified: {len(value["modules"])} subsystems, {len(actual)} source/interface roots, {sum(map(len,selectors.values()))} canonical selectors.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
