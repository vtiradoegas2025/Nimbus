#!/usr/bin/env python3
"""Generate Lin microphysics Metal sources from authoritative GLSL."""
import argparse
from generate_tke_msl import ROOT, translate


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--shader", action="append", choices=("lin_pointwise", "lin_sedimentation"))
    args = parser.parse_args()
    for name in args.shader or ("lin_pointwise", "lin_sedimentation"):
        path = ROOT / f"metal/include/compute/metal/shaders/microphysics/{name}_msl.hpp"
        source = translate(name,"microphysics").replace(
            "Generated by scripts/dev/shaders/generate_tke_msl.py",
            "Generated by scripts/dev/shaders/generate_lin_msl.py")
        if args.check:
            if not path.exists() or path.read_text() != source:
                raise SystemExit(f"{name} Metal source is stale")
        else:
            path.write_text(source)


if __name__ == "__main__":
    main()
