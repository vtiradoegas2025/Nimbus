#!/usr/bin/env python3
"""Share compensated acoustic pressure and momentum arithmetic with Metal."""

import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[3]
COMMON = ROOT / "vulkan/shaders/compute/microphysics/compensated_fma.glsl"
EOS = ROOT / "vulkan/shaders/compute/acoustic/pressure_eos.glsl"
MOMENTUM = ROOT / "vulkan/shaders/compute/acoustic/momentum_precision.glsl"
DESTINATION = ROOT / "metal/include/compute/metal/shaders/acoustics/acoustic_eos_msl.hpp"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    common = COMMON.read_text()
    source = "#define NIMBUS_PORTABLE_COMPENSATED_PRODUCT\n" + common[:common.index("vec2 df_sqrt(")] + EOS.read_text() + MOMENTUM.read_text() + "\n#undef NIMBUS_PORTABLE_COMPENSATED_PRODUCT\n"
    source = source.replace("precise ", "").replace("vec2", "float2")
    source = source.replace("floatBitsToUint(", "as_type<uint>(").replace("uintBitsToFloat(", "as_type<float>(")
    source = re.sub(r"\bout\s+int\s+(\w+)", r"thread int& \1", source)
    source = re.sub(r"\bfindMSB\((\w+)\)", r"(31 - int(clz(\1)))", source)
    source = re.sub(r"(?<![\w.])(\d*\.\d+(?:e[+-]?\d+)?|\d+e[+-]?\d+)(?![\w.])", r"\1f", source)
    expected = "#pragma once\n\n// Generated by generate_acoustic_eos_msl.py.\n// clang-format off\n"
    expected += "#define NIMBUS_ACOUSTIC_EOS_MSL " + chr(92) + "\n"
    expected += (" " + chr(92) + "\n").join(json.dumps(line + "\n") for line in source.splitlines()) + "\n"
    if args.check:
        if not DESTINATION.is_file() or DESTINATION.read_text() != expected:
            raise RuntimeError("acoustic Metal equation of state differs from the canonical source")
    else:
        DESTINATION.write_text(expected)


if __name__ == "__main__":
    main()
