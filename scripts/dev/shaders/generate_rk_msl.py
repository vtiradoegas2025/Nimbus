#!/usr/bin/env python3
"""Generate Metal RK combination arithmetic from the authoritative GLSL."""
import argparse
from generate_tke_msl import ROOT, translate


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--kernel", choices=("rk_combination", "rk_tendency"))
    args = parser.parse_args()
    for name in ((args.kernel,) if args.kernel else ("rk_combination", "rk_tendency")):
        path = ROOT / f"metal/include/compute/metal/shaders/time_stepping/{name}_msl.hpp"
        source = translate(name, "time_stepping").replace(
            "Generated by scripts/dev/shaders/generate_tke_msl.py", "Generated by scripts/dev/shaders/generate_rk_msl.py")
        if args.check:
            if not path.exists() or path.read_text() != source:
                raise SystemExit(f"{name} Metal source is stale")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(source)



if __name__ == "__main__":
    main()
