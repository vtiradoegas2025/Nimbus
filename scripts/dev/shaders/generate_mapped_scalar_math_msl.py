#!/usr/bin/env python3
"""Share compensated mapped-scalar update arithmetic with Metal."""

import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[3]
COMMON = ROOT / "vulkan/shaders/compute/microphysics/compensated_fma.glsl"
UPDATE = ROOT / "vulkan/shaders/compute/terrain/signed_scalar_update.glsl"
DESTINATION = ROOT / "metal/include/compute/metal/shaders/terrain/mapped_scalar_math_msl.hpp"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    common = COMMON.read_text()
    source = common[:common.index("vec2 df_div(")] + UPDATE.read_text()
    source = source.replace("precise ", "")
    source = source.replace("floatBitsToUint(", "as_type<uint>(").replace("uintBitsToFloat(", "as_type<float>(")
    source = re.sub(r"\bout\s+int\s+(\w+)", r"thread int& \1", source)
    source = re.sub(r"\bfindMSB\((\w+)\)", r"(31 - int(clz(\1)))", source)
    source = re.sub(r"\bvec2\b", "float2", source)
    source = re.sub(r"^(float2|float) (\w+)\(", r"inline \1 \2(", source, flags=re.MULTILINE)
    source = re.sub(r"(?<![\w.])(\d*\.\d+(?:e[+-]?\d+)?|\d+e[+-]?\d+)(?![\w.])", r"\1f", source)
    expected = "#pragma once\n\n// Generated by generate_mapped_scalar_math_msl.py.\n// clang-format off\n"
    expected += "#define NIMBUS_MAPPED_SCALAR_MATH_MSL " + chr(92) + "\n"
    expected += (" " + chr(92) + "\n").join(json.dumps(line + "\n") for line in source.splitlines()) + "\n"
    if args.check:
        if not DESTINATION.is_file() or DESTINATION.read_text() != expected:
            raise RuntimeError("mapped scalar Metal arithmetic differs from the canonical source")
    else:
        DESTINATION.write_text(expected)


if __name__ == "__main__":
    main()
