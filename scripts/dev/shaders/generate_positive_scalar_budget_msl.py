#!/usr/bin/env python3
"""Share the Cartesian positive-scalar budget arithmetic with Metal."""

import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "vulkan/shaders/compute/advection/positive_scalar_budget.glsl"
DESTINATION = ROOT / "metal/include/compute/metal/shaders/advection/positive_scalar_budget_msl.hpp"


def metal_source() -> str:
    source = SOURCE.read_text()
    source = source.replace("floatBitsToUint", "as_type<uint>")
    source = source.replace("uintBitsToFloat", "as_type<float>")
    source = source.replace("precise float", "volatile float")
    source = re.sub(r"\bout\s+int\s+(\w+)", r"thread int& \1", source)
    return re.sub(r"\bfindMSB\((\w+)\)", r"(31 - int(clz(\1)))", source)


def generated_header() -> str:
    result = "#pragma once\n\n// Generated by generate_positive_scalar_budget_msl.py.\n// clang-format off\n"
    result += "#define NIMBUS_POSITIVE_SCALAR_BUDGET_MSL " + chr(92) + "\n"
    return result + (" " + chr(92) + "\n").join(
        json.dumps(line + "\n") for line in metal_source().splitlines()) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generated_header()
    if args.check:
        if not DESTINATION.is_file() or DESTINATION.read_text() != expected:
            raise RuntimeError("Metal positive scalar budget differs from its canonical GLSL source")
    else:
        DESTINATION.write_text(expected)


if __name__ == "__main__":
    main()
