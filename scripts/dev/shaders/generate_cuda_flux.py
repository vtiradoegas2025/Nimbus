#!/usr/bin/env python3
"""Compile the embedded CUDA assist kernel; runtime needs only Vulkan/NVIDIA."""
from pathlib import Path
import argparse
import ctypes as C
import hashlib
import json

ROOT = Path(__file__).resolve().parents[3]
FLAGS = ['--gpu-architecture=compute_75', '--std=c++17', '--fmad=false',
         '--ftz=false', '--prec-div=true', '--prec-sqrt=true']


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--nvrtc', required=True, type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    library = args.nvrtc.resolve()
    builtins = sorted(library.parent.glob('libnvrtc-builtins.so.*'))
    if builtins:
        C.CDLL(str(builtins[0].resolve()), mode=C.RTLD_GLOBAL)
    compiler = C.CDLL(str(library))
    compiler.nvrtcGetErrorString.restype = C.c_char_p
    compiler.nvrtcCreateProgram.argtypes = [C.POINTER(C.c_void_p), C.c_char_p, C.c_char_p,
                                            C.c_int, C.c_void_p, C.c_void_p]
    compiler.nvrtcCompileProgram.argtypes = [C.c_void_p, C.c_int, C.POINTER(C.c_char_p)]
    compiler.nvrtcGetPTXSize.argtypes = [C.c_void_p, C.POINTER(C.c_size_t)]
    compiler.nvrtcGetPTX.argtypes = [C.c_void_p, C.c_void_p]
    compiler.nvrtcGetProgramLogSize.argtypes = [C.c_void_p, C.POINTER(C.c_size_t)]
    compiler.nvrtcGetProgramLog.argtypes = [C.c_void_p, C.c_void_p]
    compiler.nvrtcDestroyProgram.argtypes = [C.POINTER(C.c_void_p)]
    def checked(result):
        if result:
            raise RuntimeError(compiler.nvrtcGetErrorString(result).decode())
    source = ROOT / 'vulkan/cuda/retained_flux.cu'
    code = source.read_bytes()
    program = C.c_void_p()
    checked(compiler.nvrtcCreateProgram(C.byref(program), code, b'retained_flux.cu', 0, None, None))
    try:
        options = (C.c_char_p * len(FLAGS))(*(flag.encode() for flag in FLAGS))
        result = compiler.nvrtcCompileProgram(program, len(FLAGS), options)
        if result:
            size = C.c_size_t()
            checked(compiler.nvrtcGetProgramLogSize(program, C.byref(size)))
            log = C.create_string_buffer(size.value)
            checked(compiler.nvrtcGetProgramLog(program, log))
            raise RuntimeError(log.value.decode())
        size = C.c_size_t()
        checked(compiler.nvrtcGetPTXSize(program, C.byref(size)))
        buffer = C.create_string_buffer(size.value)
        checked(compiler.nvrtcGetPTX(program, buffer))
        ptx = buffer.value.decode()
    finally:
        checked(compiler.nvrtcDestroyProgram(C.byref(program)))
    major, minor = C.c_int(), C.c_int()
    checked(compiler.nvrtcVersion(C.byref(major), C.byref(minor)))
    manifest = dict(source_sha256=hashlib.sha256(code).hexdigest(),
                    ptx_sha256=hashlib.sha256(ptx.encode()).hexdigest(),
                    nvrtc_version=[major.value, minor.value], options=FLAGS,
                    entry_point='nimbus_retained_flux')
    header = ('// Generated by scripts/dev/shaders/generate_cuda_flux.py.\n#pragma once\n'
              'namespace tmv_vulkan {\n'
              f'inline constexpr char cuda_flux_sha256[] = "{manifest["ptx_sha256"]}";\n'
              'inline constexpr char cuda_flux_ptx[] = R"NIMBUS_PTX(' + ptx + ')NIMBUS_PTX";\n}\n')
    artifacts = {ROOT / 'vulkan/include/compute/cuda_retained_flux_ptx.hpp': header,
                 ROOT / 'vulkan/cuda/retained_flux.ptx': ptx,
                 ROOT / 'vulkan/cuda/manifest.json': json.dumps(manifest, indent=2) + '\n'}
    for path, contents in artifacts.items():
        if args.check:
            if path.read_text() != contents: raise RuntimeError(f'CUDA artifact drift: {path}')
        else:
            path.write_text(contents)
    print(json.dumps(manifest, indent=2))


if __name__ == '__main__':
    main()
