#!/usr/bin/env python3
"""Embed the TKE GLSL arithmetic in Metal's explicit buffer/constant wrapper."""

from pathlib import Path
import argparse
import re
from textwrap import indent

ROOT = Path(__file__).resolve().parents[3]


def shader_source(path: Path, ancestors: tuple[Path, ...] = ()) -> str:
    path = path.resolve()
    if not path.is_relative_to(ROOT / "vulkan/shaders") or path in ancestors:
        raise RuntimeError(f"invalid or cyclic shader include: {path}")
    return re.sub(r'^\s*#include\s+"([^"\n]+)"\s*$',
                  lambda match: shader_source(path.parent / match[1], (*ancestors, path)),
                  path.read_text(), flags=re.MULTILINE)


def translate(name: str, module: str = "turbulence") -> str:
    source = shader_source(ROOT / f"vulkan/shaders/compute/{module}/{name}.comp")
    buffers = re.findall(
        r"layout\s*\(\s*set\s*=\s*0\s*,\s*binding\s*=\s*(\d+)\s*\)\s*"
        r"(?:(readonly|writeonly)\s+)?buffer\s+\w+\s*\{\s*float\s+(\w+)\s*\[\s*\]\s*;\s*\}\s*;",
        source,
    )
    constants = re.search(
        r"layout\s*\(\s*push_constant\s*\)\s+uniform\s+PushConstants\s*\{(.*?)\}\s*;",
        source, re.S,
    )
    if not buffers or constants is None or [int(b[0]) for b in buffers] != list(range(len(buffers))):
        raise RuntimeError(f"{name}: unsupported shader interface")
    declarations = constants.group(1)
    fields = re.findall(r"(?:int|uint|float|int64_t|uint64_t)\s+(\w+)\s*;", declarations)
    body = source[constants.end():source.index("void main()")].strip()
    body = re.sub(r"\b(" + "|".join(fields) + r")\b", r"pc.\1", body)
    body = body.replace("precise ", "")
    for glsl_type, metal_type in (("uint64_t", "ulong"), ("int64_t", "long")):
        declarations = re.sub(r"\b" + glsl_type + r"\b", metal_type, declarations)
        body = re.sub(r"\b" + glsl_type + r"\b", metal_type, body)
    body = re.sub(r"\b(?:out|inout)\s+(vec2|float|int)\s+(\w+)", r"thread \1& \2", body)
    body = body.replace("floatBitsToUint(", "as_type<uint>(").replace("uintBitsToFloat(", "as_type<float>(")
    symbol = "".join(part.capitalize() for part in name.split("_"))
    pointer = lambda access: "device const float*" if access == "readonly" else "device float*"
    members = "\n".join(f"    {pointer(access)} {field};" for _, access, field in buffers)
    arguments = ",\n".join(f"    {pointer(access)} {field} [[buffer({index})]]" for index, access, field in buffers)
    initialization = ", ".join(field for _, _, field in buffers) + ", pc"
    rendered = f'''#pragma once
// Generated by scripts/dev/shaders/generate_tke_msl.py; edit the GLSL source.
namespace nimbus::metal::shaders
{{
inline constexpr char k{symbol}Msl[] = R"msl(
#include <metal_stdlib>
using namespace metal;
using vec2 = float2;
struct {symbol}PushConstants
{{{declarations}}};
struct {symbol}Program
{{
{members}
    constant {symbol}PushConstants& pc;
{indent(body, '    ')}
}};
kernel void {name}(
{arguments},
    constant {symbol}PushConstants& pc [[buffer({len(buffers)})]],
    uint gid [[thread_position_in_grid]])
{{
    {symbol}Program program{{{initialization}}};
    program.evaluate(gid);
}}
)msl";
}} // namespace nimbus::metal::shaders
'''
    start = rendered.index('R"msl(') + len('R"msl(')
    end = rendered.index(')msl";', start)
    metal_source = rendered[start:end]
    if len(metal_source) > 60000:
        chunks = [metal_source[i:i + 16000] for i in range(0, len(metal_source), 16000)]
        expression = 'std::string(R"msl(' + chunks[0] + ')msl")'
        expression += ''.join(' +\nR"msl(' + chunk + ')msl"' for chunk in chunks[1:])
        declaration = f"inline const std::string k{symbol}MslStorage = {expression};\ninline const char* const k{symbol}Msl = k{symbol}MslStorage.c_str();"
        first = rendered.index(f"inline constexpr char k{symbol}Msl[]")
        rendered = rendered[:first] + declaration + rendered[end + len(')msl";'):]
        rendered = rendered.replace('#pragma once', '#pragma once\n#include <string>', 1)
    return rendered


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--kernel", choices=("tke_closure", "tke_tendency", "collocated_sgs"))
    args = parser.parse_args()
    for name in ((args.kernel,) if args.kernel else ("tke_closure", "tke_tendency", "collocated_sgs")):
        path = ROOT / f"metal/include/compute/metal/shaders/turbulence/{name}_msl.hpp"
        expected = translate(name)
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise RuntimeError(f"generated TKE Metal source drifted: {path}")
        else:
            path.write_text(expected)


if __name__ == "__main__":
    main()
