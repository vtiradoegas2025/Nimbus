#!/usr/bin/env python3
"""Generate Metal's Milbrandt kernel from the authoritative GLSL arithmetic."""
import argparse
from pathlib import Path
from generate_tke_msl import translate, ROOT


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    names = ("milbrandt_warm_rain", "milbrandt_cloud_adjustment", "milbrandt_melting", "milbrandt_cold", "milbrandt_sedimentation")
    parser.add_argument("--kernel", choices=names)
    args = parser.parse_args()
    for name in ((args.kernel,) if args.kernel else names):
        path = ROOT / f"metal/include/compute/metal/shaders/microphysics/{name}_msl.hpp"
        source = translate(name, "microphysics").replace(
            "Generated by scripts/dev/shaders/generate_tke_msl.py", "Generated by scripts/dev/shaders/generate_milbrandt_msl.py")
        if args.check:
            if not path.exists() or path.read_text() != source:
                raise SystemExit(f"Milbrandt Metal source is stale: {name}")
        else:
            path.write_text(source)



if __name__ == "__main__":
    main()
