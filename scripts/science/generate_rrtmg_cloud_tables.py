#!/usr/bin/env python3
"""Translate pinned AER RRTMG cloud tables into a native C++ header.

The generated header is checked in and is the only artifact used by Nimbus at
build or runtime. This maintainer tool exists solely to make the numeric-table
provenance reproducible when the pinned upstream RRTMG revision changes.
"""

from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path


def numbers(body: str) -> list[float]:
    body = re.sub(r"!.*", "", body)
    body = body.replace("&", "").replace("_rb", "")
    tokens = re.findall(r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eEdD][-+]?\d+)?", body)
    return [float(token.replace("D", "E").replace("d", "e")) for token in tokens]


def vector(source: str, name: str, selector: str) -> list[float]:
    pattern = rf"{re.escape(name)}\s*\({selector}\)\s*=\s*\(/(.*?)/\)"
    match = re.search(pattern, source, flags=re.DOTALL | re.IGNORECASE)
    if match is None:
        raise ValueError(f"missing {name}({selector})")
    return numbers(match.group(1))


def band_table(source: str, name: str, first_band: int, bands: int, rows: int) -> list[float]:
    result: list[float] = []
    for band in range(first_band, first_band + bands):
        values = vector(source, name, rf":\s*,\s*{band}")
        if len(values) != rows:
            raise ValueError(f"{name} band {band} has {len(values)} values; expected {rows}")
        result.extend(values)
    return result


def fixed_vector(source: str, name: str, selector: str, expected: int) -> list[float]:
    values = vector(source, name, selector)
    if len(values) != expected:
        raise ValueError(f"{name}({selector}) has {len(values)} values; expected {expected}")
    return values


def format_array(name: str, values: list[float], width: int = 4) -> str:
    lines = [f"inline constexpr std::array<double, {len(values)}> {name}{{{{"]
    for offset in range(0, len(values), width):
        row = ", ".join(format(value, ".17g") for value in values[offset : offset + width])
        lines.append(f"    {row},")
    lines.append("}};")
    return "\n".join(lines)


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--longwave-init", type=Path, required=True)
    parser.add_argument("--shortwave-init", type=Path, required=True)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("src/radiation/schemes/rrtmg/generated/rrtmg_cloud_tables.hpp"),
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the checked-in output differs instead of rewriting it",
    )
    args = parser.parse_args()

    longwave = args.longwave_init.read_text(encoding="utf-8")
    shortwave = args.shortwave_init.read_text(encoding="utf-8")
    tables = [
        format_array("longwave_liquid_absorption", band_table(longwave, "absliq1", 1, 16, 58)),
        format_array("longwave_ice_intercept", fixed_vector(longwave, "absice1", rf"1\s*,\s*:", 5)),
        format_array("longwave_ice_inverse_radius", fixed_vector(longwave, "absice1", rf"2\s*,\s*:", 5)),
        format_array("shortwave_liquid_extinction", band_table(shortwave, "extliq1", 16, 14, 58)),
        format_array("shortwave_liquid_single_scattering_albedo", band_table(shortwave, "ssaliq1", 16, 14, 58)),
        format_array("shortwave_liquid_asymmetry", band_table(shortwave, "asyliq1", 16, 14, 58)),
        format_array("shortwave_ice_extinction_intercept", fixed_vector(shortwave, "abari", r":", 5)),
        format_array("shortwave_ice_extinction_inverse_radius", fixed_vector(shortwave, "bbari", r":", 5)),
        format_array("shortwave_ice_absorption_intercept", fixed_vector(shortwave, "cbari", r":", 5)),
        format_array("shortwave_ice_absorption_radius", fixed_vector(shortwave, "dbari", r":", 5)),
        format_array("shortwave_ice_asymmetry_intercept", fixed_vector(shortwave, "ebari", r":", 5)),
        format_array("shortwave_ice_asymmetry_radius", fixed_vector(shortwave, "fbari", r":", 5)),
    ]
    text = f"""// Generated by scripts/science/generate_rrtmg_cloud_tables.py.
// AER RRTMG numeric data only; do not edit by hand.
// longwave init SHA-256: {digest(args.longwave_init)}
// shortwave init SHA-256: {digest(args.shortwave_init)}
#pragma once

#include <array>

namespace tmv::rrtmg::cloud_tables
{{

{chr(10).join(tables)}

}} // namespace tmv::rrtmg::cloud_tables
"""
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != text:
            raise SystemExit(f"generated RRTMG cloud tables differ from {args.output}")
        return
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
