export interface PyodideCatalogEntry {
  /** What the user types in an import statement. */
  readonly importName: string;
  /** What loadPackage is given. Differs from importName for aliased packages. */
  readonly packageName: string;
  /** Why someone analysing storm output would reach for it. */
  readonly purpose: string;
  /** Loaded at boot, one click away, or reachable only through micropip. */
  readonly availability: "preloaded" | "bundled" | "micropip";
}

